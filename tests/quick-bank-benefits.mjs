import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { dashboardOverview } from "../dist/apps/quick-worker/src/dashboard-data.js";
import { BANK_BENEFITS_JS } from "../dist/apps/quick-worker/src/dashboard-bank-benefits-js.js";
import { DASH_HTML } from "../dist/apps/quick-worker/src/dashboard-html.js";
const db=new DatabaseSync(":memory:");
db.exec(`
CREATE TABLE quick_manual_entries(owner_id TEXT,id TEXT,account_id TEXT,amount_minor INTEGER,currency TEXT,payment_method TEXT,kind TEXT,occurred_at TEXT,merchant TEXT,bank_label TEXT,revision INTEGER,deleted_at TEXT);
CREATE TABLE quick_shortcut_expenses(owner_id TEXT,id TEXT,amount_minor INTEGER,currency TEXT,payment_method TEXT,kind TEXT,occurred_at TEXT,merchant TEXT,bank_label TEXT,revision INTEGER,deleted_at TEXT);
CREATE TABLE quick_movement_categories(owner_id TEXT,source TEXT,movement_id TEXT,category TEXT,subcategory TEXT);
CREATE TABLE quick_auto_categories(owner_id TEXT,source TEXT,movement_id TEXT,category TEXT,subcategory TEXT,confidence REAL,needs_review INTEGER);
`);
const add=db.prepare("INSERT INTO quick_shortcut_expenses (owner_id,id,amount_minor,currency,payment_method,kind,occurred_at,merchant,bank_label,revision) VALUES (?,?,?,?,?,?,?,?,?,0)");
add.run("A","1",200000,"COP","debit_card","purchase","2026-11-04T20:00:00Z","Chokis","Plata Pay");
add.run("A","2",3000000,"COP","bank_transfer","purchase","2026-11-04T20:01:00Z","Pago de prestamo a amiga","Daviplata");
add.run("A","3",500000,"COP","bank_transfer","purchase","2026-11-04T20:02:00Z","Bre-B a tercero","Bancolombia");
add.run("B","4",9900000,"COP","debit_card","purchase","2026-11-04T20:03:00Z","Chokis","Davivienda");
const api={prepare(sql){const stmt=db.prepare(sql);let args=[];return {bind(...v){args=v;return this;},async first(){return stmt.get(...args)||null;},async all(){return {results:stmt.all(...args)}}};}};
const data=await (await dashboardOverview(api,"A")).json();
assert.equal(data.movementCount,3);
assert.equal(data.bankDaily.length,1);
assert.equal(data.bankDaily[0].bank,"Plata Pay");
assert.equal(data.bankDaily[0].minor,"200000");
assert.equal(data.pendingTransferReviewMinor,"500000");
assert.equal(data.debtPaymentsMinor,"3000000");
assert.ok(!JSON.stringify(data).includes("Davivienda"));
assert.match(DASH_HTML,/bank-insights-list/);
assert.match(DASH_HTML,/Plata Pay/);
assert.match(DASH_HTML,/benefit-cashback/);
assert.match(DASH_HTML,/no se registran ingresos|No se registran ingresos/i);
new Function(BANK_BENEFITS_JS);
assert.ok(BANK_BENEFITS_JS.includes("Math.pow(1+r/100,d/365)"));
assert.ok(!/localStorage|indexedDB|sessionStorage/.test(BANK_BENEFITS_JS),"No persist input balances");
console.log("Bank expenses: spend-only, isolation, safe estimate UI passed");
