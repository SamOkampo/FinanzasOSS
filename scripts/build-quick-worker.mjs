import {mkdir, readFile, writeFile} from "node:fs/promises";
import {createRequire} from "node:module";
import {build} from "esbuild";

const require = createRequire(import.meta.url);

const asset = await build({
  entryPoints: ["apps/quick-worker/src/statement-pdf-worker.ts"],
  bundle: true,
  platform: "browser",
  format: "iife",
  external: ["fs", "path"],
  target: ["safari16", "es2022"],
  minify: true,
  write: false,
});
const wasm = await readFile(require.resolve("@neslinesli93/qpdf-wasm/dist/qpdf.wasm"));
const [pdfRenderer,pdfWorker] = await Promise.all(["pdf.min.mjs","pdf.worker.min.mjs"].map(name=>
  readFile(require.resolve("pdfjs-dist/legacy/build/" + name),"utf8")));
const output = "apps/quick-worker/.generated";
await mkdir(output, {recursive: true});
await writeFile(output + "/statement-pdf-worker-asset.ts",
  "// Generated by scripts/build-quick-worker.mjs.\n" +
  "export const STATEMENT_PDF_WORKER_JS = " + JSON.stringify(asset.outputFiles[0].text) + ";\n" +
  "export const STATEMENT_PDF_WASM_BASE64 = " + JSON.stringify(wasm.toString("base64")) + ";\n" +
  "export const PDFJS_RENDERER_JS = " + JSON.stringify(pdfRenderer) + ";\n" +
  "export const PDFJS_WORKER_JS = " + JSON.stringify(pdfWorker) + ";\n");

const bundlePath = process.argv[2];
if (bundlePath) {
  await build({
    entryPoints: ["apps/quick-worker/src/index.ts"],
    bundle: true,
    platform: "browser",
    format: "esm",
    target: "es2022",
    minify: true,
    outfile: bundlePath,
  });
}
